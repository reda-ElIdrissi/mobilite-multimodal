CREATE TABLE regle (
    id uuid PRIMARY KEY,
    settings jsonb NOT NULL,
    version integer NOT NULL DEFAULT 1
);
CREATE TABLE promotion (
    code varchar(64) PRIMARY KEY,
    settings jsonb NOT NULL,
    version integer NOT NULL DEFAULT 1
);
CREATE TABLE promotion_mode (
    code varchar(64) NOT NULL REFERENCES promotion(code),
    mode varchar(16) NOT NULL,
    PRIMARY KEY (code, mode)
);
CREATE TABLE devis (
    id uuid PRIMARY KEY,
    user_id varchar(255) NOT NULL,
    reservation_id uuid UNIQUE,
    status varchar(16) NOT NULL CHECK (status IN ('ISSUED','CLAIMED','EXPIRED','CONSUMED','VOID')),
    created_at timestamptz NOT NULL,
    expires_at timestamptz NOT NULL,
    total_minor bigint NOT NULL CHECK (total_minor >= 0),
    itinerary_hash char(64) NOT NULL,
    snapshot jsonb NOT NULL,
    version integer NOT NULL DEFAULT 0
);
CREATE TABLE ligne_devis (
    id uuid PRIMARY KEY,
    devis_id uuid NOT NULL REFERENCES devis(id),
    allocation_id uuid NOT NULL,
    snapshot jsonb NOT NULL,
    UNIQUE (devis_id, allocation_id)
);
CREATE TABLE devis_ajustement (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ligne_id uuid NOT NULL REFERENCES ligne_devis(id),
    snapshot jsonb NOT NULL
);
