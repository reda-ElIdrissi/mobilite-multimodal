CREATE TABLE villes (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nom varchar(255) NOT NULL UNIQUE
);
CREATE TABLE categories (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nom varchar(255) NOT NULL UNIQUE
);
CREATE TABLE vehicules (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id bigint NOT NULL,
    marque varchar(255) NOT NULL,
    modele varchar(255) NOT NULL,
    immatriculation varchar(255) NOT NULL,
    couleur varchar(255) NOT NULL,
    ville_id bigint NOT NULL REFERENCES villes,
    categorie_id bigint NOT NULL REFERENCES categories,
    added_at date NOT NULL,
    is_available boolean NOT NULL
);
CREATE TABLE ville_vehicule (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ville_id bigint NOT NULL REFERENCES villes,
    vehicule_id bigint NOT NULL REFERENCES vehicules,
    debut date,
    fin date
);
CREATE TABLE locations (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id bigint NOT NULL,
    renter_id bigint NOT NULL,
    depart_id bigint NOT NULL REFERENCES villes,
    destination_id bigint NOT NULL REFERENCES villes,
    date_debut date NOT NULL,
    date_fin date NOT NULL,
    status smallint NOT NULL,
    rating_owner integer,
    rating_renter integer,
    joined_at date NOT NULL
);
CREATE TABLE vehiculelocations (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vehicule_id bigint NOT NULL REFERENCES vehicules,
    location_id bigint NOT NULL REFERENCES locations,
    debut date,
    fin date
);
CREATE TABLE penalites (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    frais double precision NOT NULL,
    type varchar(255) NOT NULL
);
CREATE TABLE location_penalites (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    location_id bigint NOT NULL REFERENCES locations,
    penalite_id bigint NOT NULL REFERENCES penalites
);
